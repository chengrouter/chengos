#!/usr/bin/env bash
#
# procd init-script template for services installed by deploy/openwrt/.
#
# This file is sourced, never executed. ow_procd_render prints an
# /etc/init.d/<name> script; callers upload it and run `enable`.
#
# Restarts are bounded: procd's respawn THRESHOLD TIMEOUT RETRY stops the
# instance after RETRY crashes that each happen within THRESHOLD seconds of
# start, instead of looping forever (e.g. on AddrInUse). Memory/OOM limits are
# deliberately not set here: they are used only after being proven per image.

# Values written into the init script must not need shell quoting beyond a
# plain single-quoted string, and must never carry newlines.
ow_procd_check_value() {
    local label="$1" value="$2"
    case "$value" in
        *"'"*|*$'\n'*|*$'\r'*) ow_die "${label} must not contain quotes or newlines: ${value}" ;;
    esac
}

# ow_procd_render NAME COMMAND DIRECTORY DATA_DIR RESPAWN ENV_ARRAY_NAME ARGS_ARRAY_NAME
#   NAME      service name (also the procd instance name)
#   COMMAND   absolute path of the binary on the router
#   DIRECTORY working directory
#   DATA_DIR  directory created before start ("" to skip)
#   RESPAWN   "THRESHOLD TIMEOUT RETRY", e.g. "3600 5 5"
#   ENV/ARGS  names of bash arrays holding KEY=VALUE entries / extra argv
ow_procd_render() {
    local name="$1" command="$2" directory="$3" data_dir="$4" respawn="$5"
    local -n _env_ref="$6"
    local -n _args_ref="$7"
    local item env_line="" args_line=""

    [[ "$name" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] || ow_die "invalid service name: ${name}"
    [[ "$command" == /* ]] || ow_die "service command must be an absolute path: ${command}"
    [[ "$respawn" =~ ^[0-9]+\ [0-9]+\ [0-9]+$ ]] || ow_die "respawn must be 'THRESHOLD TIMEOUT RETRY': ${respawn}"
    ow_procd_check_value "command" "$command"
    ow_procd_check_value "directory" "$directory"
    ow_procd_check_value "data dir" "$data_dir"
    for item in "${_env_ref[@]}"; do
        [[ "$item" =~ ^[A-Za-z_][A-Za-z0-9_]*= ]] || ow_die "env entry must be KEY=VALUE: ${item}"
        ow_procd_check_value "env entry" "$item"
        env_line+=" '${item}'"
    done
    for item in "${_args_ref[@]}"; do
        ow_procd_check_value "argument" "$item"
        args_line+=" '${item}'"
    done

    cat <<EOF
#!/bin/sh /etc/rc.common
# Generated by ChengOS deploy/openwrt/deploy.sh; redeploy instead of editing.
START=99
STOP=10
USE_PROCD=1

start_service() {
EOF
    if [[ -n "$data_dir" ]]; then
        printf "\tmkdir -p '%s'\n" "$data_dir"
    fi
    printf "\tprocd_open_instance '%s'\n" "$name"
    printf "\tprocd_set_param command '%s'%s\n" "$command" "$args_line"
    if [[ -n "$env_line" ]]; then
        printf "\tprocd_set_param env%s\n" "$env_line"
    fi
    printf "\tprocd_set_param directory '%s'\n" "$directory"
    printf "\tprocd_set_param respawn %s\n" "$respawn"
    printf "\tprocd_set_param term_timeout 15\n"
    printf "\tprocd_set_param stdout 1\n"
    printf "\tprocd_set_param stderr 1\n"
    printf "\tprocd_close_instance\n"
    printf "}\n"
}
